#!/usr/bin/env python3
"""Regenerate the sc_tools package from sc-rnaseq-wf/docker/sc_tools.

Usage: python sync.py [path/to/sc-rnaseq-wf]   (default: ../sc-rnaseq-wf)

Everything under src/sc_tools/, plus requirements*.txt and entry-points.txt,
is generated by this script -- edit upstream, not here.

Transforms applied to the upstream scripts:
  * scripts/main/<name> and scripts/utility/helpers.py -> src/sc_tools/<name>.py
  * `sys.path.append("/opt/scripts/utility")` + `from helpers import ...`
    -> `from sc_tools.helpers import ...`
  * `/opt/resources/<file>` -> path inside the installed package
  * the `if __name__ == "__main__":` block is wrapped in `cli()` (declaring
    `global args`, which some upstream functions read) so each script is
    exposed as a console script (`sc-<name>`)
"""

import re
import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent
PKG = REPO / "src" / "sc_tools"
SKIP_CLI = {"DEPRECATED_annotate_cells"}
# argparse is stdlib; the PyPI backport pinned upstream must not be installed
SKIP_REQS = {"argparse"}


def header(rel_path: str, sha: str) -> str:
    return f"# Generated by sync.py from sc-rnaseq-wf@{sha[:12]}:{rel_path} -- do not edit.\n"


def add_header(text: str, hdr: str) -> str:
    if text.startswith("#!"):
        first, _, rest = text.partition("\n")
        return f"{first}\n{hdr}{rest}"
    return hdr + text


def transform_script(text: str, name: str) -> str:
    text = re.sub(r'^sys\.path\.append\("/opt/scripts/utility"\)\n', "", text, flags=re.M)
    text = re.sub(r"^from helpers import", "from sc_tools.helpers import", text, flags=re.M)
    if name not in SKIP_CLI:
        main_guard = 'if __name__ == "__main__":'
        if text.count(f"\n{main_guard}\n") != 1:
            sys.exit(f"error: {name}: expected exactly one top-level `{main_guard}` block")
        # upstream helpers read the module-level `args` set in the main guard
        text = text.replace(f"\n{main_guard}\n", "\ndef cli():\n    global args\n")
        text = text.rstrip("\n") + f"\n\n\n{main_guard}\n    cli()\n"
    return text


def transform_helpers(text: str) -> str:
    # count_cell_cycle_genes already defines `root = pathlib.Path(__file__).parent`
    return re.sub(r'"/opt/resources/([^"]+)"', r'root / "resources" / "\1"', text)


def cli_name(name: str) -> str:
    return "sc-" + name.replace("_", "-")


def main() -> None:
    wf = Path(sys.argv[1] if len(sys.argv) > 1 else REPO.parent / "sc-rnaseq-wf").resolve()
    src = wf / "docker" / "sc_tools"
    if not src.is_dir():
        sys.exit(f"error: {src} not found")
    sha = subprocess.run(
        ["git", "-C", str(wf), "rev-parse", "HEAD"], capture_output=True, text=True, check=True
    ).stdout.strip()
    build_env = dict(
        line.split("=", 1)
        for line in (src / "build.env").read_text().splitlines()
        if "=" in line and not line.startswith("#")
    )

    if PKG.exists():
        shutil.rmtree(PKG)
    (PKG / "resources").mkdir(parents=True)

    clis = []
    for path in sorted((src / "scripts" / "main").iterdir()):
        if path.name.startswith(".") or not path.is_file():
            continue
        name = path.stem
        if not name.isidentifier():
            sys.exit(f"error: {path.name} is not a valid Python module name")
        text = transform_script(path.read_text(), name)
        (PKG / f"{name}.py").write_text(add_header(text, header(f"docker/sc_tools/scripts/main/{path.name}", sha)))
        if name not in SKIP_CLI:
            clis.append(name)

    helpers = transform_helpers((src / "scripts" / "utility" / "helpers.py").read_text())
    (PKG / "helpers.py").write_text(add_header(helpers, header("docker/sc_tools/scripts/utility/helpers.py", sha)))

    for res in sorted((src / "resources").iterdir()):
        if res.is_file():
            shutil.copy2(res, PKG / "resources" / res.name)

    leftover = [p.name for p in PKG.glob("*.py") if re.search(r"^[^#\n]*/opt/", p.read_text(), flags=re.M)]
    if leftover:
        sys.exit(f"error: unhandled /opt/ paths remain in: {', '.join(leftover)}")

    (PKG / "__init__.py").write_text(
        header("docker/sc_tools", sha)
        + f'__version__ = "{build_env["SC_TOOLS_VERSION"]}"\n'
        + f'__upstream_commit__ = "{sha}"\n'
    )

    reqs = [
        line
        for line in (src / "requirements.txt").read_text().splitlines()
        if line.strip() and re.split(r"[=<>!~ ]", line, maxsplit=1)[0].lower() not in SKIP_REQS
    ]
    (REPO / "requirements.txt").write_text("\n".join(reqs) + "\n")
    (REPO / "requirements-mmc.txt").write_text(
        "cell_type_mapper @ git+https://github.com/AllenInstitute/cell_type_mapper.git"
        f"@v{build_env['CELL_TYPE_MAPPER_VERSION']}\n"
    )
    (REPO / "entry-points.txt").write_text(
        "[console_scripts]\n" + "".join(f"{cli_name(n)} = sc_tools.{n}:cli\n" for n in clis)
    )

    print(f"synced sc_tools {build_env['SC_TOOLS_VERSION']} from {wf} @ {sha[:12]} ({len(clis)} CLIs)")


if __name__ == "__main__":
    main()
